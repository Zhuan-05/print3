"""Configuration validation and atomic private .env writer."""
import os
import re
import tempfile
from pathlib import Path
from urllib.parse import urlsplit

ENV_PATH = Path(__file__).resolve().parents[1] / ".env"


def validate(values: dict[str, str]) -> None:
    if not re.fullmatch(r"\d+:[A-Za-z0-9_-]+", values["BOT_TOKEN"]):
        raise ValueError("BOT_TOKEN 格式不正确；请检查 BotFather 提供的 Token。")
    if not re.fullmatch(r"-?[1-9]\d*", values["ADMIN_CHAT_ID"]):
        raise ValueError("ADMIN_CHAT_ID 必须是非零整数：群组为负数，管理员私聊为正数。")
    admin_ids = [x.strip() for x in values["ADMIN_USER_IDS"].split(",")]
    if not admin_ids or any(not re.fullmatch(r"[1-9]\d*", x) for x in admin_ids):
        raise ValueError("ADMIN_USER_IDS 请用英文逗号分隔正整数 Telegram 用户 ID。")
    if len(set(admin_ids)) != len(admin_ids):
        raise ValueError("ADMIN_USER_IDS 中有重复 ID。")
    if not re.fullmatch(r"[a-fA-F0-9]{64}", values["WEBHOOK_SECRET"]):
        raise ValueError("WEBHOOK_SECRET 必须是 64 位十六进制字符。")
    if not re.fullmatch(r"[A-Za-z0-9_-]+", values["GOOGLE_FORM_ID"]):
        raise ValueError("GOOGLE_FORM_ID 格式不正确，请使用 describeForm() 输出的 Form ID。")
    form_url = urlsplit(values["GOOGLE_FORM_URL"])
    if (form_url.scheme != "https" or form_url.netloc != "docs.google.com" or
            not re.fullmatch(r"/forms/d/e/[A-Za-z0-9_-]+/viewform", form_url.path) or
            form_url.query or form_url.fragment):
        raise ValueError("GOOGLE_FORM_URL 应为完整公开 viewform 链接，且不带 query 参数。")
    entries = (values["FORM_TELEGRAM_ENTRY"], values["FORM_BINDING_ENTRY"])
    if any(not re.fullmatch(r"entry\.\d+", x) for x in entries):
        raise ValueError("表单预填字段必须是 entry.数字 格式。")
    if entries[0] == entries[1]:
        raise ValueError("Telegram ID 与绑定令牌不能使用同一个 entry ID。")
    if not values["DATABASE_PATH"].strip() or any(c in values["DATABASE_PATH"] for c in "\r\n"):
        raise ValueError("DATABASE_PATH 不能为空，也不能包含换行。")
    if not values["PAYMENT_INSTRUCTIONS"].strip() or len(values["PAYMENT_INSTRUCTIONS"]) > 1500:
        raise ValueError("PAYMENT_INSTRUCTIONS 需填写内容，长度不能超过 1500 字符。")
    if any(c in values["PAYMENT_INSTRUCTIONS"] for c in "\r\n"):
        raise ValueError("收款说明请写成单行，避免 .env 解析错误。")


def dotenv_value(value: str) -> str:
    """Quote values so spaces, #, quotes and backslashes remain one value."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_env(values: dict[str, str]) -> None:
    lines = ["# Generated by auto_setup.py. Keep private; never commit this file."]
    lines.extend(f"{key}={dotenv_value(value)}" for key, value in values.items())
    content = "\n".join(lines) + "\n"
    ENV_PATH.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=".env.", dir=ENV_PATH.parent, text=True)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temp_name, ENV_PATH)
        ENV_PATH.chmod(0o600)
    except Exception:
        try:
            os.unlink(temp_name)
        except FileNotFoundError:
            pass
        raise
